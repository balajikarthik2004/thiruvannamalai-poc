export function getTemple(slug: string) {
  return temples.find((t) => t.slug === slug);
}

/**
 * CSS `background` for a temple thumbnail. The temple's gradient is painted as
 * a second layer underneath the photo, so a slow or broken image URL degrades
 * to the gradient instead of leaving an empty box.
 */
export function templeThumb(t: Temple, position = "center") {
  const gradient = `linear-gradient(135deg, ${t.gradientFrom}, ${t.color})`;
  const src = t.thumb ?? t.image;
  // Quote the URL: Commons file names often contain "(" ")" or "," which break an unquoted url().
  return src ? `url("${src.replace(/"/g, "%22")}") ${position} / cover no-repeat, ${gradient}` : gradient;
}

export function statusColor(s: CrowdStatus) {
  if (s === "LOW") return "var(--status-low)";
  if (s === "MODERATE") return "var(--status-mod)";
  return "var(--status-high)";
}

export function statusLabel(s: CrowdStatus) {
  if (s === "LOW") return "Low crowd";
  if (s === "MODERATE") return "Moderate";
  if (s === "HIGH") return "High";
  return "Critical";
}

export function forecastFor(t: Temple) {
  const start = 5.5; // Force start at 5:30 AM
  const [closeH, closeM] = t.closeTime.split(":").map(Number);
  let end = closeH + closeM / 60;
  if (end < start) end += 24;

  const times: number[] = [];
  for (let h = start; h <= end; h += 0.5) {
    times.push(h);
  }

  return times.map((h) => {
    // Use Gaussian curves for an incredibly smooth and natural flow
    const morningPeak = Math.exp(-Math.pow(h - 10.5, 2) / 8);
    const eveningPeak = Math.exp(-Math.pow(h - 18.5, 2) / 8);

    let base = 25 + morningPeak * 60 + eveningPeak * 50;

    if (t.afternoonClose && t.afternoonOpen) {
      const [acH, acM] = t.afternoonClose.split(":").map(Number);
      const [aoH, aoM] = t.afternoonOpen.split(":").map(Number);
      const ac = acH + acM / 60;
      const ao = aoH + aoM / 60;

      if (h >= ac && h <= ao) {
        // Smooth dip down to a minimum of 15 (instead of 0) during afternoon closure
        const mid = (ac + ao) / 2;
        const dip = 1 - Math.abs(h - mid) / ((ao - ac) / 2);
        base = base - (base - 15) * dip;
      }
    }

    const variance = (t.crowdPct - 50) * 0.3;
    const val = Math.max(12, Math.min(98, base + variance + Math.sin(h * t.id) * 4));

    const hour = Math.floor(h);
    const mins = h % 1 !== 0 ? "30" : "00";
    const actualHour = hour % 24;
    const ampm = actualHour >= 12 ? "PM" : "AM";
    const displayHour = actualHour > 12 ? actualHour - 12 : actualHour === 0 ? 12 : actualHour;

    return {
      hour: h,
      label: `${displayHour}:${mins} ${ampm}`,
      pct: Math.round(val),
      wait: Math.round(val * 0.8),
    };
  });
}
